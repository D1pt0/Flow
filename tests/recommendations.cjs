const fs=require('fs'),vm=require('vm'),assert=require('assert');
const source=fs.readFileSync('android/assets/web/app.js','utf8');
const recent=Array.from({length:40},(_,i)=>({name:'Recent '+i,url:'new'+i,year:'2026'}));
const older=Array.from({length:40},(_,i)=>({name:'Favourite '+i,url:'old'+i,year:'2010'}));
let ranked=older.concat(recent);
const context={Date,Map,Set,Number,year:item=>item.year,normalizeSearch:s=>s.toLowerCase(),title:item=>item.name,flowPicks:new Set(),recommendationItems:()=>ranked,stableFeedOrder:[],feedLimit:24};
vm.createContext(context);
vm.runInContext(source.slice(source.indexOf('function mixRecommendations('),source.indexOf('function searchItems(')),context);
const mixed=context.mixRecommendations(ranked,2026);
assert.equal(mixed[0].url,'new0');assert.equal(mixed[1].url,'new1');assert.equal(mixed[2].url,'old0');
assert.equal(mixed.length,80);assert.equal(new Set(mixed.map(i=>i.url)).size,80);
const first=context.stableRecommendations().slice(0,24).map(i=>i.url);
ranked=[{name:'New arrival',url:'arrival',year:'2026'},...ranked];context.feedLimit=48;
