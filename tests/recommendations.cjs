assert.deepEqual(next.slice(0,24).map(i=>i.url),first);
assert(next.slice(24).some(i=>i.year==='2026'));assert(next.slice(24).some(i=>i.year==='2010'));
assert.equal(context.mixRecommendations(older,2026).length,40);
assert.equal(context.mixRecommendations(recent,2026).length,40);
const unrated={name:'Unrated',url:'u',year:'2026'},low={name:'Low',url:'l',year:'2026',chartMatch:{rating:5}},good={name:'Good',url:'g',year:'2026',chartMatch:{rating:8}};
assert.deepEqual(context.mixRecommendations([low,unrated,good],2026).map(i=>i.url),['g','u','l']);
console.log('PASS recent/classic mix, recent rating priority, stable pagination, unique titles and single-age catalogs.');
